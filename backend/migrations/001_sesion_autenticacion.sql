BEGIN;

CREATE TABLE sesion_autenticacion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profesional_id INTEGER NOT NULL,
    token_hash TEXT NOT NULL,
    creada_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    vence_en TIMESTAMPTZ NOT NULL,
    revocada_en TIMESTAMPTZ,
    CONSTRAINT fk_sesion_autenticacion_profesional FOREIGN KEY (profesional_id)
        REFERENCES profesional (id) ON DELETE RESTRICT,
    CONSTRAINT uq_sesion_autenticacion_token_hash UNIQUE (token_hash),
    CONSTRAINT ck_sesion_autenticacion_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_sesion_autenticacion_vencimiento CHECK (vence_en > creada_en),
    CONSTRAINT ck_sesion_autenticacion_revocacion
        CHECK (revocada_en IS NULL OR revocada_en >= creada_en)
);

CREATE INDEX idx_sesion_autenticacion_profesional
    ON sesion_autenticacion (profesional_id);

COMMIT;
