-- Esquema inicial PostgreSQL del MVP de seguimiento psicopedagogico.
-- Basado en los dos PDF de docs y en los formularios de frontend/src/modulos/pacientes.
-- Ejecutar una sola vez sobre una base vacia, previamente creada:
--   psql -U <usuario> -d <base_de_datos> -v ON_ERROR_STOP=1 -f backend/init.sql
-- La transaccion evita dejar un esquema incompleto si alguna sentencia falla.
-- Los cambios posteriores al esquema deben realizarse mediante migraciones.
--
-- Convenciones para la futura API:
--   Paciente.fechaNacimiento -> paciente.fecha_nacimiento.
--   Paciente.fechaInicio -> paciente.fecha_inicio_seguimiento.
--   Los campos opcionales vacios del frontend se convierten a NULL,
--   especialmente escolaridad.fecha_fin; los ID nuevos los genera PostgreSQL.
--   password_hash recibe el hash calculado por el backend, nunca la clave original.
--   El backend valida la pertenencia al profesional autenticado en cada operacion.
--   Al vincular una observacion, debe validar que objetivo y sesion sean del mismo
--   paciente, tambien al modificar esos vinculos o reasignar sus registros padre.
--
-- Los PDF no fijan los valores de los estados. Para esta implementacion:
--   Objetivo: activo, cumplido, cerrado (cierre sin cumplimiento).
--   Informe: borrador, finalizado (revisado por el profesional).
-- No se limita a una unica escolaridad vigente: esa decision sigue abierta en el PDF.
-- Se restringen los borrados de registros referenciados para conservar el historial.
-- Profesional y Paciente pueden desactivarse mediante activo = FALSE.

BEGIN;

CREATE TABLE profesional (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre TEXT NOT NULL CHECK (btrim(nombre) <> ''),
    apellido TEXT NOT NULL CHECK (btrim(apellido) <> ''),
    email TEXT NOT NULL CHECK (btrim(email) <> ''),
    password_hash TEXT NOT NULL CHECK (btrim(password_hash) <> ''),
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

-- Un mismo correo no puede registrar dos cuentas por diferencias de mayusculas.
CREATE UNIQUE INDEX uq_profesional_email ON profesional (lower(btrim(email)));

CREATE TABLE paciente (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    profesional_id INTEGER NOT NULL,
    nombre TEXT NOT NULL CHECK (btrim(nombre) <> ''),
    apellido TEXT NOT NULL CHECK (btrim(apellido) <> ''),
    fecha_nacimiento DATE NOT NULL,
    fecha_inicio_seguimiento DATE NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_paciente_profesional FOREIGN KEY (profesional_id)
        REFERENCES profesional (id) ON DELETE RESTRICT,
    CONSTRAINT ck_paciente_fechas
        CHECK (fecha_inicio_seguimiento >= fecha_nacimiento)
);

CREATE TABLE admision (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL UNIQUE,
    fecha DATE NOT NULL,
    motivo_consulta TEXT NOT NULL CHECK (btrim(motivo_consulta) <> ''),
    antecedentes_personales TEXT,
    antecedentes_evolutivos TEXT,
    antecedentes_salud TEXT,
    grupo_familiar TEXT,
    tratamientos_actuales TEXT,
    observaciones TEXT,
    CONSTRAINT fk_admision_paciente FOREIGN KEY (paciente_id)
        REFERENCES paciente (id) ON DELETE RESTRICT
);

CREATE TABLE escolaridad (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL,
    institucion TEXT NOT NULL CHECK (btrim(institucion) <> ''),
    nivel TEXT NOT NULL CHECK (btrim(nivel) <> ''),
    grado_anio_sala TEXT NOT NULL CHECK (btrim(grado_anio_sala) <> ''),
    modalidad TEXT NOT NULL CHECK (btrim(modalidad) <> ''),
    jornada TEXT,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    apoyos TEXT,
    observaciones TEXT,
    referente_nombre TEXT,
    referente_rol TEXT,
    referente_contacto TEXT,
    CONSTRAINT fk_escolaridad_paciente FOREIGN KEY (paciente_id)
        REFERENCES paciente (id) ON DELETE RESTRICT,
    CONSTRAINT ck_escolaridad_fechas
        CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

-- Son contactos externos del paciente; no son cuentas de acceso a la aplicacion.
CREATE TABLE profesional_tratante (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL,
    nombre TEXT NOT NULL CHECK (btrim(nombre) <> ''),
    especialidad TEXT NOT NULL CHECK (btrim(especialidad) <> ''),
    contacto TEXT,
    fecha_inicio DATE NOT NULL,
    fecha_fin DATE,
    observaciones TEXT,
    CONSTRAINT fk_profesional_tratante_paciente FOREIGN KEY (paciente_id)
        REFERENCES paciente (id) ON DELETE RESTRICT,
    CONSTRAINT ck_profesional_tratante_fechas
        CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio)
);

CREATE TABLE objetivo (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL,
    descripcion TEXT NOT NULL CHECK (btrim(descripcion) <> ''),
    fecha_inicio DATE NOT NULL,
    estado TEXT NOT NULL DEFAULT 'activo',
    fecha_cierre DATE,
    observaciones_generales TEXT,
    CONSTRAINT fk_objetivo_paciente FOREIGN KEY (paciente_id)
        REFERENCES paciente (id) ON DELETE RESTRICT,
    CONSTRAINT ck_objetivo_estado CHECK (estado IN ('activo', 'cumplido', 'cerrado')),
    CONSTRAINT ck_objetivo_fechas
        CHECK (fecha_cierre IS NULL OR fecha_cierre >= fecha_inicio),
    CONSTRAINT ck_objetivo_cierre CHECK (
        (estado = 'activo' AND fecha_cierre IS NULL)
        OR (estado IN ('cumplido', 'cerrado') AND fecha_cierre IS NOT NULL)
    )
);

CREATE TABLE sesion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL,
    fecha DATE NOT NULL,
    presente BOOLEAN NOT NULL,
    nota_general TEXT,
    CONSTRAINT fk_sesion_paciente FOREIGN KEY (paciente_id)
        REFERENCES paciente (id) ON DELETE RESTRICT
);

-- La observacion admite uno o varios campos, sin exigir una estructura completa.
-- Una sesion puede no tener observaciones; cada observacion tiene a lo sumo un objetivo.
CREATE TABLE observacion (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sesion_id INTEGER NOT NULL,
    objetivo_id INTEGER,
    contexto TEXT,
    conducta_observable TEXT,
    intervencion TEXT,
    resultado TEXT,
    nota_libre TEXT,
    CONSTRAINT fk_observacion_sesion FOREIGN KEY (sesion_id)
        REFERENCES sesion (id) ON DELETE RESTRICT,
    CONSTRAINT fk_observacion_objetivo FOREIGN KEY (objetivo_id)
        REFERENCES objetivo (id) ON DELETE RESTRICT,
    CONSTRAINT ck_observacion_contenido CHECK (
        nullif(btrim(contexto), '') IS NOT NULL
        OR nullif(btrim(conducta_observable), '') IS NOT NULL
        OR nullif(btrim(intervencion), '') IS NOT NULL
        OR nullif(btrim(resultado), '') IS NOT NULL
        OR nullif(btrim(nota_libre), '') IS NOT NULL
    )
);

CREATE TABLE informe (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    paciente_id INTEGER NOT NULL,
    titulo TEXT NOT NULL CHECK (btrim(titulo) <> ''),
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    estado TEXT NOT NULL DEFAULT 'borrador',
    periodo_desde DATE NOT NULL,
    periodo_hasta DATE NOT NULL,
    contenido TEXT NOT NULL CHECK (btrim(contenido) <> ''),
    asistido_ia BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT fk_informe_paciente FOREIGN KEY (paciente_id)
        REFERENCES paciente (id) ON DELETE RESTRICT,
    CONSTRAINT ck_informe_estado CHECK (estado IN ('borrador', 'finalizado')),
    CONSTRAINT ck_informe_periodo CHECK (periodo_hasta >= periodo_desde)
);

-- Indices para las claves foraneas, el listado de pacientes y el seguimiento por fecha.
-- La FK de admision ya queda indexada por su restriccion UNIQUE.
CREATE INDEX idx_paciente_profesional_nombre
    ON paciente (profesional_id, apellido, nombre);
CREATE INDEX idx_escolaridad_paciente_fecha
    ON escolaridad (paciente_id, fecha_inicio DESC);
CREATE INDEX idx_profesional_tratante_paciente
    ON profesional_tratante (paciente_id);
CREATE INDEX idx_objetivo_paciente_estado
    ON objetivo (paciente_id, estado);
CREATE INDEX idx_sesion_paciente_fecha
    ON sesion (paciente_id, fecha DESC, id DESC);
CREATE INDEX idx_observacion_sesion ON observacion (sesion_id);
CREATE INDEX idx_observacion_objetivo ON observacion (objetivo_id);
CREATE INDEX idx_informe_paciente_fecha
    ON informe (paciente_id, fecha DESC, id DESC);

-- La cronologia y la evolucion de objetivos se consultan a partir de sesion y
-- observacion. Solo persiste el texto confirmado de las transcripciones en
-- nota_general o en los campos de observacion; el audio se procesa temporalmente.

COMMIT;
